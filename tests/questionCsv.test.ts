import { describe, it, expect } from 'vitest';
import { parseQuestionCsv, prepareImport } from '../src/lib/questionCsv';
import { GAME_LIMITS } from '../src/constants/gameLimits';

describe('parseQuestionCsv', () => {
  it('parses number,question header and quoted rows with commas and doubled quotes', async () => {
    const csv = [
      'number,question',
      '1,"Why did Rahul bring a spoon, fork, and panic to class?"',
      '2,"Explain ""the incident"" in five words."',
    ].join('\n');

    const rows = await parseQuestionCsv(csv);
    expect(rows).toEqual([
      'Why did Rahul bring a spoon, fork, and panic to class?',
      'Explain "the incident" in five words.',
    ]);
  });

  it('handles BOM, CRLF line endings, blank lines, and # comment lines', async () => {
    const csv = '\uFEFF# generated by AI\r\nnumber,question\r\n\r\n1,"First question?"\r\n# ignore me\r\n2,"Second question?"\r\n\r\n';
    const rows = await parseQuestionCsv(csv);
    expect(rows).toEqual(['First question?', 'Second question?']);
  });

  it('handles question-only header, headerless one-column, and headerless number,text files', async () => {
    const qHeader = await parseQuestionCsv('question\n"Single header row"\n"Second row"');
    expect(qHeader).toEqual(['Single header row', 'Second row']);

    const oneCol = await parseQuestionCsv('No header line one\nNo header line two');
    expect(oneCol).toEqual(['No header line one', 'No header line two']);

    const numbered = await parseQuestionCsv('1,First numbered\n2,Second numbered');
    expect(numbered).toEqual(['First numbered', 'Second numbered']);
  });

  it('parses semicolon-separated CSV with a number;question header', async () => {
    const csv = 'number;question\n1;"What happened at gate two?"\n2;"Who slept through the pitch?"';
    const rows = await parseQuestionCsv(csv);
    expect(rows).toEqual(['What happened at gate two?', 'Who slept through the pitch?']);
  });

  it('keeps headerless unquoted line with commas intact', async () => {
    const csv = 'Describe X, Y and Z';
    const rows = await parseQuestionCsv(csv);
    expect(rows).toEqual(['Describe X, Y and Z']);
  });

  it('strips leading list markers like 1. and 2) and collapses newlines inside quotes to spaces', async () => {
    const csv = [
      'number,question',
      '1,"1. First item\nacross lines"',
      '2,"2) Second item"',
    ].join('\n');

    const rows = await parseQuestionCsv(csv);
    expect(rows).toEqual(['First item across lines', 'Second item']);
  });

  it('caps output at MAX_QUESTIONS_PER_GAME * 4 returned rows on huge input', async () => {
    const total = GAME_LIMITS.MAX_QUESTIONS_PER_GAME * 5;
    const lines = ['number,question'];
    for (let i = 1; i <= total; i++) {
      lines.push(`${i},"Question number ${i}?"`);
    }
    const rows = await parseQuestionCsv(lines.join('\n'));
    expect(rows).toHaveLength(GAME_LIMITS.MAX_QUESTIONS_PER_GAME * 4);
  });
});

describe('prepareImport', () => {
  it('validates length/empty, deduplicates case-insensitively, caps at remainingSlots, and collapses whitespace', () => {
    const overLong = 'x'.repeat(GAME_LIMITS.MAX_QUESTION_LENGTH + 1);
    const raw = [
      '   ',
      overLong,
      'Already asked?',
      '  Fresh   question   one? ',
      'fresh question one?',
      'Fresh question two?',
      'Fresh question three?',
    ];

    const result = prepareImport(raw, ['already asked?'], 2);

    expect(result.accepted).toEqual(['Fresh question one?', 'Fresh question two?']);
    expect(result.skipped).toHaveLength(5);
    expect(result.skipped[0].reason).toBeTruthy();
    expect(result.skipped[1].reason).toContain(String(GAME_LIMITS.MAX_QUESTION_LENGTH));
    expect(result.skipped[2].reason).toBe('Duplicate question.');
    expect(result.skipped[3].reason).toBe('Duplicate question.');
    expect(result.skipped[4].reason).toBe(
      `No free question slots left (maximum ${GAME_LIMITS.MAX_QUESTIONS_PER_GAME}).`,
    );
  });
});

